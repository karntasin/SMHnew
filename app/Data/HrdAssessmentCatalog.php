    private static function section(string $title, array $items): array
    {
        return [
            'title' => $title,
            'weight' => 1,
            'items' => array_map(function ($item) {
                if (is_array($item)) {
                    return ['prompt' => $item[0], 'reverse' => (bool) ($item[1] ?? false)];
                }

                return ['prompt' => $item, 'reverse' => false];
            }, $items),
        ];
    }
